import React from 'react';
import { useFinance } from '../context/FinanceContext';
import { formatCurrency } from '../utils/finance';
import { translate } from '../utils/i18n';
import LanguageSelector from './LanguageSelector';
import ShapeGrid from './ShapeGrid';
import '../home.css';

function HomePage(props) {
  const finance = useFinance();
  const t = (text) => translate(text, finance.language);
  const theme = props.theme || finance.theme;
  const onToggleTheme = props.onToggleTheme || finance.toggleTheme;
  const onNavigateToDashboard = props.onNavigateToDashboard || (() => {
    if (!finance.isLoggedIn) finance.navigateTo('login', '/login');
    else finance.navigateTo('dashboard', '/dashboard');
  });
  const transactions = Array.isArray(finance.transactions) ? finance.transactions : [];
  const expenses = transactions.reduce((total, tx) => (
    Number(tx.amount) < 0 ? total + Math.abs(Number(tx.amount)) : total
  ), 0);
  const income = transactions.reduce((total, tx) => (
    Number(tx.amount) > 0 ? total + Number(tx.amount) : total
  ), 0);
  const recentTransactions = [...transactions]
    .sort((a, b) => String(b.date || '').localeCompare(String(a.date || '')))
    .slice(0, 4);
  const categories = Object.entries(finance.categoryTotals || {})
    .sort((a, b) => b[1] - a[1])
    .slice(0, 4);
  const navigateToFeatures = () => document.getElementById('features')?.scrollIntoView({ behavior: 'smooth' });
  const scrollToTop = () => window.scrollTo({ top: 0, behavior: 'smooth' });
  const dateLocale = { en: 'en-IN', hi: 'hi-IN', pa: 'pa-IN' }[finance.language] || 'en-IN';

  const features = [
    {
      number: '01',
      title: 'Expense Tracking',
      description: 'Record your income and expenses in one place. Keep track of transactions, amounts, categories, and spending activity without scattered spreadsheets.',
    },
    {
      number: '02',
      title: 'Smart Receipt Management',
      description: 'Upload a receipt image, preview it, and review editable example details. Receipt reading is simulated; enter details yourself.',
    },
    {
      number: '03',
      title: 'Budget Management',
      description: 'Review spending across categories and compare expenses with the budget information available in the app.',
    },
    {
      number: '04',
      title: 'Financial Health Score',
      description: 'See a score calculated from the income and expenses currently recorded in your dashboard.',
    },
    {
      number: '05',
      title: 'Financial Insights',
      description: 'Explore spending suggestions generated by the app’s existing JavaScript rules, not an external AI service.',
    },
    {
      number: '06',
      title: 'Budget Forecasting',
      description: 'Review spending totals and a simple overspending indicator. These estimates are guidance, not guaranteed predictions.',
    },
    {
      number: '07',
      title: 'Spending Activity Calendar',
      description: 'View recorded expenses by date to understand when you log spending and spot routine patterns.',
    },
    {
      number: '08',
      title: 'Transaction History',
      description: 'Review recent income and expenses together, with amounts, categories, and dates.',
    },
    {
      number: '09',
      title: 'AI Finance Coach',
      description: 'Ask about spending and budgeting; responses come from the app’s built-in rules and are general guidance.',
    },
    {
      number: '10',
      title: 'Financial Overview Dashboard',
      description: 'Review your recorded balance, category totals, financial health score, insights, and recent transactions.',
    },
    {
      number: '11',
      title: 'Income & Expense Management',
      description: 'Add income or expense entries through a form and see money coming in separately from money going out.',
    },
    {
      number: '12',
      title: 'A Cleaner View of Your Finances',
      description: 'Access your available finance tools from one organized dashboard.',
    },
  ];

  return (
    <div className={`home-root ${theme === 'light' ? 'theme-light' : 'theme-dark'}`} data-theme={theme}>
      <header className="landing-nav">
        <button type="button" className="landing-brand" onClick={scrollToTop}>
          <span className="landing-brand-mark">FT</span>
          <span>FinTrack AI</span>
        </button>
        <nav className="landing-nav-links" aria-label="Main navigation">
          <button type="button" onClick={scrollToTop}>{t('Home')}</button>
          <button type="button" onClick={onNavigateToDashboard}>{t('Dashboard')}</button>
          <button
            type="button"
            onClick={() => {
              if (!finance.isLoggedIn) finance.navigateTo('login', '/login');
              else finance.navigateTo('river', '/money-river');
            }}
          >
            {t('Money River')}
          </button>
          <button
            type="button"
            onClick={() => {
              if (!finance.isLoggedIn) finance.navigateTo('login', '/login');
              else finance.navigateTo('jars', '/jars');
            }}
          >
            {t('Money Jars')}
          </button>
          <button
            type="button"
            onClick={() => {
              if (!finance.isLoggedIn) finance.navigateTo('login', '/login');
              else finance.navigateTo('split', '/split');
            }}
          >
            {t('Split Bills')}
          </button>
        </nav>
        <div className="landing-nav-actions">
          <LanguageSelector className="home-language-selector" />
          <button
            type="button"
            className="landing-theme-toggle"
            onClick={onToggleTheme}
            aria-label={theme === 'dark' ? 'Switch to light theme' : 'Switch to dark theme'}
          >
            {theme === 'dark' ? 'Light' : 'Dark'}
          </button>
          <button type="button" className="landing-button landing-button-small" onClick={onNavigateToDashboard}>
            {t('Open Dashboard')}
          </button>
        </div>
      </header>

      <main>
        <section className="landing-hero">
          <div className="landing-hero-grid" aria-hidden="true">
            <ShapeGrid
              shape="square"
              direction="diagonal"
              lineColor="#94a3b8"
              hoverColor="#10b981"
              hoverFillColor="#10b981"
              fillOpacity={0.25}
              cellSize={40}
              speed={0.5}
              rainbow={false}
              glow={0.2}
            />
          </div>
          <div className="landing-hero-copy">
            <p className="landing-eyebrow">{t('Personal finance, made clear')}</p>
            <h1>{t('Take Control of Your Money.')}</h1>
            <p className="landing-hero-description">
              {t('Track expenses, manage budgets, and understand your spending with simple financial insights.')}
            </p>
            <div className="landing-hero-actions">
              <button type="button" className="landing-button" onClick={onNavigateToDashboard}>
                {t('Open Dashboard')}
              </button>
              <button type="button" className="landing-button landing-button-secondary" onClick={navigateToFeatures}>
                {t('Explore Features')}
              </button>
            </div>
          </div>
          <section className="dashboard-preview" aria-label={t('Dashboard preview')}>
            <div className="preview-header">
              <div>
                <p className="preview-kicker">{t('FinTrack AI')}</p>
                <h2>{t('Your finances at a glance')}</h2>
              </div>
              <button type="button" className="preview-open-button" onClick={onNavigateToDashboard}>
                {t('Dashboard')} <span aria-hidden="true">↗</span>
              </button>
            </div>
            <div className="preview-metrics">
              <article className="preview-metric">
                <span>{t('Recorded income')}</span>
                <strong>{formatCurrency(income)}</strong>
              </article>
              <article className="preview-metric">
                <span>{t('Recorded expenses')}</span>
                <strong>{formatCurrency(-expenses)}</strong>
              </article>
              <article className="preview-metric">
                <span>{t('Recorded balance')}</span>
                <strong>{formatCurrency(income - expenses, true)}</strong>
              </article>
            </div>
            <div className="preview-content">
              <div className="preview-category-list">
                <h3>{t('Spending by category')}</h3>
                {categories.length ? categories.map(([name, amount]) => (
                  <div className="preview-category-row" key={name}>
                    <span>{t(name)}</span>
                    <strong>{formatCurrency(amount)}</strong>
                  </div>
                )) : <p className="preview-empty">{t('No spending recorded yet.')}</p>}
              </div>
              <div className="preview-transaction-list">
                <h3>{t('Recent transactions')}</h3>
                {recentTransactions.length ? recentTransactions.map((tx, index) => (
                  <div className="preview-transaction-row" key={tx.id ?? `${tx.date}-${index}`}>
                    <div>
                      <strong>{tx.merchant || t('Transaction')}</strong>
                      <span>{t(tx.category || 'Uncategorized')} · {tx.date
                        ? new Date(`${tx.date}T00:00:00`).toLocaleDateString(dateLocale, { day: 'numeric', month: 'short' })
                        : ''}</span>
                    </div>
                    <strong className={Number(tx.amount) < 0 ? 'preview-expense' : 'preview-income'}>
                      {formatCurrency(tx.amount, true)}
                    </strong>
                  </div>
                )) : <p className="preview-empty">{t('Add a transaction to see it here.')}</p>}
              </div>
            </div>
            <p className="preview-note">{t('Preview uses your current app data stored in this browser.')}</p>
          </section>
        </section>

        <section className="landing-features" id="features">
          <div className="landing-section-heading">
            <p className="landing-eyebrow">{t('Simple tools for everyday finances')}</p>
            <h2>{t('Everything You Need to Stay in Control of Your Money')}</h2>
            <p>{t('From tracking daily expenses to understanding your financial habits, FinTrack AI brings your personal finances together in one place.')}</p>
          </div>
          <div className="landing-feature-grid">
            {features.map((feature) => (
              <article className="landing-feature-card" key={feature.number}>
                <span className="landing-feature-number">{feature.number}</span>
                <h3>{t(feature.title)}</h3>
                <p>{t(feature.description)}</p>
              </article>
            ))}
          </div>
        </section>

        <section className="landing-final-cta">
          <div>
            <p className="landing-eyebrow">{t('Start with a clearer view')}</p>
            <h2>{t('Make your next money decision with confidence.')}</h2>
            <p>{t('Log your transactions and review your spending in the dashboard.')}</p>
          </div>
          <button type="button" className="landing-button" onClick={onNavigateToDashboard}>
            {t('Open Dashboard')}
          </button>
        </section>
      </main>

      <footer className="landing-footer">
        <button type="button" className="landing-brand" onClick={scrollToTop}>
          <span className="landing-brand-mark">FT</span>
          <span>FinTrack AI</span>
        </button>
        <div className="landing-footer-team">
          <span>{t('Project team')}</span>
          <strong>SAHAJ · CHIRAG · DHRUV · KESHAV</strong>
        </div>
        <nav aria-label="Footer navigation">
          <button type="button" onClick={scrollToTop}>{t('Home')}</button>
          <button type="button" onClick={onNavigateToDashboard}>{t('Dashboard')}</button>
        </nav>
        <a
          className="landing-university-link"
          href="https://www.chitkara.edu.in/"
          target="_blank"
          rel="noreferrer"
        >
          {t('Chitkara University, Punjab')}
        </a>
      </footer>
    </div>
  );
}

export default HomePage;
